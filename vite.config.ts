import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';
import plates from './public/plates/plates.json' with { type: 'json' };
import sounds from './public/sounds/sounds.json' with { type: 'json' };
import { serviceWorker } from './src/sw/worker.ts';

/** Files from public/ the game needs offline, besides the plates and sounds their manifests list. */
const PUBLIC_FILES = [
  './',
  'index.html',
  'manifest.webmanifest',
  'fonts/quicksand-latin-var.woff2',
  'icons/favicon.svg',
  'icons/icon.svg',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
  'icons/apple-touch-icon.png',
  'plates/plates.json',
  'sounds/sounds.json',
];

/**
 * Writes dist/sw.js: the offline service worker (src/sw/worker.ts), called with
 * this build's version and every file to keep: the public files above, every
 * plate and sound clip in their manifests, and the hashed scripts and styles.
 */
function offline(): Plugin {
  return {
    name: 'vivi-offline',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = [
        ...PUBLIC_FILES,
        ...plates.plates.map((p) => `plates/${p.file}`),
        ...[...sounds.giggles, ...sounds.tada].map((f) => `sounds/${f}`),
        ...Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'index.html'),
      ];
      // Public files keep their names when they change, so each build is a new version.
      const version = Date.now().toString(36);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Vivi Fashion Dresses: offline play. Generated by vite.config.ts.\n(${serviceWorker.toString()})(${JSON.stringify(version)}, ${JSON.stringify([...new Set(files)], null, 1)});\n`,
      });
    },
  };
}

export default defineConfig({
  // Relative base so dist/ works from a domain root or a GitHub Pages subpath.
  base: './',
  plugins: [offline()],
  build: {
    target: 'es2022',
    assetsInlineLimit: 0,
  },
  test: {
    include: ['tests/unit/**/*.test.ts'],
    environment: 'node',
    // Process CSS instead of stubbing it, so tests can read stylesheets with ?raw.
    css: { include: [/\.css(\?|$)/] },
  },
});
